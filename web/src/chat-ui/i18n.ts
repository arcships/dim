export type HostMessageKey = keyof typeof hostMessagesEn
type ChatUiCatalog = Record<ChatUiMessageKey | HostMessageKey | ChatUiToolLabelKey, string>

/** Everything the shared timeline reads, in English. */
export const chatUiMessagesEn: ChatUiCatalog = { ...chatUiEn, ...hostMessagesEn, ...toolMessagesEn }
/** The Chinese catalog ships with the Web's own `zh-CN` messages; this pins it to the same keys. */
export const chatUiMessagesZhCN: ChatUiCatalog = chatUiZhCN

i18n.global.mergeLocaleMessage("en", chatUiMessagesEn)

export const toolTranslate: ChatUiToolTranslate = (key, params) => i18n.global.t(key, params ?? {})

export function createChatUiI18n(): ChatUiI18n {
  return {
    locale: computed(() => i18n.global.locale.value),
    t: (key, params) => i18n.global.t(key, params ?? {}),
  }
}
